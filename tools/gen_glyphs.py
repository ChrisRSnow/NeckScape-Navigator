#!/usr/bin/env python3
"""Generates notation/Glyphs.kt: vector outlines for the score, tab and PDF.

Text and music symbols are drawn as filled paths, so the screen and the PDF
look identical on every platform and the PDF needs no embedded fonts.

  - Music symbols: Bravura (SIL Open Font License 1.1, (c) Steinberg Media
    Technologies GmbH), https://github.com/steinbergmedia/bravura
  - Text: DejaVu Sans / Sans Bold (Bitstream Vera licence + public domain).

Usage (needs fontTools):  python3 tools/gen_glyphs.py Bravura.otf DejaVuSans.ttf DejaVuSans-Bold.ttf
"""
import sys
from pathlib import Path

from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont

OUT = Path(__file__).resolve().parent.parent / "app/src/main/kotlin/com/crsnow/neckscape/notation/Glyphs.kt"

# SMuFL code points used by the engraver.
MUSIC = {
    0xE050: "gClef", 0xE052: "gClef8vb", 0xE062: "fClef", 0xE064: "fClef8vb",
    0xE0A2: "noteheadWhole", 0xE0A4: "noteheadBlack",
    0xE260: "flat", 0xE261: "natural", 0xE262: "sharp", 0xE263: "doubleSharp", 0xE264: "doubleFlat",
}
TEXT = [chr(c) for c in range(0x20, 0x7F)] + [chr(c) for c in range(0xA0, 0x100)] + list("♯♭♮△–—♩’…")


class PathPen(BasePen):
    """Records an outline as "M x y L x y Q x y x y C … Z" in font units, y pointing down."""

    def __init__(self, glyphset):
        super().__init__(glyphset)
        self.out = []

    def _pt(self, *pts):
        return " ".join(f"{round(x)} {round(-y)}" for x, y in pts)

    def _moveTo(self, p):
        self.out.append("M" + self._pt(p))

    def _lineTo(self, p):
        self.out.append("L" + self._pt(p))

    def _qCurveToOne(self, p1, p2):
        self.out.append("Q" + self._pt(p1, p2))

    def _curveToOne(self, p1, p2, p3):
        self.out.append("C" + self._pt(p1, p2, p3))

    def _closePath(self):
        self.out.append("Z")


def glyphs(path, chars):
    font = TTFont(path)
    cmap, gs, hmtx = font.getBestCmap(), font.getGlyphSet(), font["hmtx"]
    upm = font["head"].unitsPerEm
    rows = []
    for ch in chars:
        name = cmap.get(ord(ch))
        if name is None:
            continue
        pen = PathPen(gs)
        gs[name].draw(pen)
        rows.append((ch, hmtx[name][0], "".join(pen.out)))
    return upm, rows


def snake(name):
    return "".join("_" + c if c.isupper() else c.upper() for c in name).replace("8VB", "_8VB")


def kotlin_char(ch):
    if ch in "\\'":
        return "'\\" + ch + "'"
    return f"'\\u{ord(ch):04X}'" if ord(ch) > 0x7E or ch == " " else f"'{ch}'"


def font_block(name, doc, upm, rows):
    lines = [f"    /** {doc} */", f"    val {name}: GlyphFont by lazy {{", f"        GlyphFont({upm}f, mapOf("]
    for ch, adv, d in rows:
        lines.append(f'            {kotlin_char(ch)} to Glyph({adv}f, "{d}"),')
    lines += ["        ))", "    }"]
    return lines


def main():
    bravura, sans, bold = sys.argv[1:4]
    music_upm, music = glyphs(bravura, [chr(c) for c in MUSIC])
    out = [
        "// GENERATED by tools/gen_glyphs.py — do not edit.",
        "// Music symbols: Bravura, SIL Open Font License 1.1, (c) Steinberg Media Technologies GmbH.",
        "// Text: DejaVu Sans, Bitstream Vera licence. See THIRD_PARTY_NOTICES.md.",
        "package com.crsnow.neckscape.notation",
        "",
        "internal object Glyphs {",
        *[f"    const val {snake(n)}: Char = '\\u{c:04X}'" for c, n in MUSIC.items()],
        "",
        *font_block("music", "Bravura (SMuFL): 1 em = 4 staff spaces.", music_upm, music),
        "",
        *font_block("sans", "DejaVu Sans.", *glyphs(sans, TEXT)),
        "",
        *font_block("sansBold", "DejaVu Sans Bold.", *glyphs(bold, TEXT)),
        "}",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
