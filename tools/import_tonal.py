#!/usr/bin/env python3
"""Regenerate TonalData.kt from tonal's chord and scale dictionaries.

tonal (https://github.com/tonaljs/tonal, MIT, (c) 2015 danigb) keeps its
dictionaries as TypeScript arrays of interval lists. This transcribes them
into Kotlin; Chords.kt / Scales.kt then add whichever entries the hand-written
lists don't already cover, so re-running this never duplicates anything.

    tools/import_tonal.py            # fetch tonal@main and rewrite TonalData.kt
"""
import re
import urllib.request
from pathlib import Path

BASE = "https://raw.githubusercontent.com/tonaljs/tonal/main/packages"
OUT = Path(__file__).resolve().parent.parent / "app/src/main/kotlin/com/crsnow/neckscape/theory/TonalData.kt"
PERFECT = {1, 4, 5}


def fetch(path):
    with urllib.request.urlopen(f"{BASE}/{path}") as r:
        return r.read().decode()


def entries(ts):
    """Each `["1P 3M 5P", "name", "alias" ...]` row whose first field is an interval list."""
    rows = re.findall(r'\[\s*((?:"[^"]*",?\s*)+)\]', ts)
    parsed = [re.findall(r'"([^"]*)"', row) for row in rows]
    return [p for p in parsed if re.fullmatch(r"(\d+[PMmAd]+ ?)+", p[0])]


def interval(tonal):
    """tonal "7m" / "11A" / "5d" → NeckScape "b7" / "#11" / "b5"."""
    num, quality = re.fullmatch(r"(\d+)([PMmAd]+)", tonal).groups()
    perfect = (int(num) - 1) % 7 + 1 in PERFECT
    if quality in ("P", "M"):
        acc = ""
    elif quality == "m":
        acc = "b"
    elif quality[0] == "A":
        acc = "#" * len(quality)
    else:  # diminished: one flat below perfect, two below major
        acc = "b" * (len(quality) + (0 if perfect else 1))
    return acc + num


def symbol(alias):
    """tonal's ASCII alias → NeckScape style: "M7b9" → "maj7♭9", "Maddb9" → "add♭9"."""
    s = re.sub(r"^M(?=7|9|13)", "maj", alias)
    s = re.sub(r"^M", "", s)
    return re.sub(r"[b#](?=\d)", lambda m: "♭" if m.group() == "b" else "♯", s)


def kt(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    chords = []
    for ivs, name, *aliases in entries(fetch("chord-type/data.ts")):
        alias = (aliases[0].split() or [""])[0] if aliases else ""
        intervals = " ".join(interval(i) for i in ivs.split())
        chords.append(f"        Triple({kt(symbol(alias))}, {kt(name)}, {kt(intervals)}),")

    scales = []
    for ivs, name, *_ in entries(fetch("scale-type/data.ts")):
        intervals = " ".join(interval(i) for i in ivs.split())
        scales.append(f"        {kt(name[:1].upper() + name[1:])} to {kt(intervals)},")

    OUT.write_text(
        "// GENERATED by tools/import_tonal.py — do not edit by hand.\n"
        "// Source: tonal (https://github.com/tonaljs/tonal), MIT License, Copyright (c) 2015 danigb.\n\n"
        "package com.crsnow.neckscape.theory\n\n"
        "internal object TonalData {\n"
        "    /** Symbol, name (may be blank), intervals. */\n"
        "    val chords: List<Triple<String, String, String>> = listOf(\n"
        + "\n".join(chords)
        + "\n    )\n\n"
        "    /** Name to intervals. */\n"
        "    val scales: List<Pair<String, String>> = listOf(\n"
        + "\n".join(scales)
        + "\n    )\n}\n"
    )
    print(f"{OUT}: {len(chords)} chords, {len(scales)} scales")


if __name__ == "__main__":
    main()
